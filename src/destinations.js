const byKeyword = DESTINATIONS.flatMap((dest) => dest.keywords.map((keyword) => ({ keyword, dest })));

// Country names that also have more specific city entries, e.g. "Goa, India" should pick Goa
const COUNTRY_KEYWORDS = new Set(['india', 'japan', 'france', 'italy', 'usa', 'united states', 'uk', 'united kingdom', 'england', 'britain', 'spain', 'thailand', 'indonesia', 'korea', 'south korea', 'egypt', 'turkey', 'turkiye', 'türkiye', 'greece', 'switzerland', 'australia', 'vietnam', 'uae', 'emirates']);

export function findDestination(input) {
  const text = ` ${input.toLowerCase().replace(/[^\p{L}\p{N}'\s]/gu, ' ').replace(/\s+/g, ' ')} `;
  // In "Delhi to Manali" or "Goa from Mumbai", the starting point isn't the destination
  const isOrigin = (index) => text.slice(0, index).endsWith(' from') ||
    text.slice(index).match(/^ [^ ]+(?: [^ ]+)? to /) !== null;
  const matches = byKeyword
    .map((entry) => ({ ...entry, index: text.indexOf(` ${entry.keyword} `) }))
    .filter(({ index }) => index !== -1)
    // Prefer destinations over origins, cities over countries, then whichever is mentioned first, then the longer keyword
    .sort((a, b) =>
      isOrigin(a.index) - isOrigin(b.index) ||
      COUNTRY_KEYWORDS.has(a.keyword) - COUNTRY_KEYWORDS.has(b.keyword) ||
      a.index - b.index ||
      b.keyword.length - a.keyword.length
    );
  return matches.length ? matches[0].dest : null;
}

// Reads "5 days", "5-day", "a week" or "weekend" from free text
export function parseRequestedDays(input) {
  const text = input.toLowerCase();
  const match = text.match(/(\d+)\s*-?\s*(day|night)/);
  if (match) return parseInt(match[1], 10);
  if (/\b(a|one) week\b/.test(text)) return 7;
  if (/\bweekend\b/.test(text)) return 2;
  return null;
}

export function buildItinerary(dest, requestedDays) {
  const available = dest.days.length;
  const count = requestedDays && requestedDays > 0 ? Math.min(requestedDays, available) : available;

  const itinerary = {
    destination_id: dest.id,
    trip_title: dest.title,
    destination: dest.destination,
    duration_days: count,
    days: dest.days.slice(0, count).map((day, i) => ({
      day: i + 1,
      title: day.title,
      stops: day.stops.map(([time, name, category, cost_estimate, notes], s) => ({
        id: `d${i + 1}-s${s + 1}`,
        name,
        time,
        category,
        cost_estimate,
        notes,
      })),
    })),
  };

  if (requestedDays && requestedDays > available) {
    itinerary.notice = `Showing our curated ${available}-day plan for ${dest.name}. Use the extra days to slow down, revisit favourites or take a day trip.`;
  }
  return itinerary;
}
